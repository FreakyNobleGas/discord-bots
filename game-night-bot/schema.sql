-- The one schema for the game night bot AND the game night website (../game-night-website).
-- Both projects share this Neon Postgres database; nothing syncs between them.
-- Idempotent: the bot runs it on startup, the site runs it with `npm run db:init`.
-- Changing a table here means updating bot/database.py and the site's
-- src/lib/types.ts + src/lib/server/**/postgres.ts too.

-- Written by the bot (/add-game, /remove-game) and the site's admin page.
CREATE TABLE IF NOT EXISTS games (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id    BIGINT      NOT NULL,
    name        TEXT        NOT NULL,
    rawg_id     INTEGER,
    rawg_slug   TEXT,
    cover_url   TEXT        NOT NULL DEFAULT '',
    genre_tags  JSONB       NOT NULL DEFAULT '[]'::jsonb,  -- RAWG genre names
    added_by    TEXT        NOT NULL,
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS games_guild_idx ON games (guild_id);
CREATE UNIQUE INDEX IF NOT EXISTS games_guild_rawg_uniq ON games (guild_id, rawg_id)
    WHERE rawg_id IS NOT NULL;

-- Written by the bot (/log-session) and the site's admin page.
CREATE TABLE IF NOT EXISTS sessions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id     INTEGER     NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    played_on   TIMESTAMPTZ NOT NULL DEFAULT now(),
    logged_by   TEXT,
    notes       TEXT
);
CREATE INDEX IF NOT EXISTS sessions_game_idx ON sessions (game_id);

-- Written by Grok Bot through the site's API (POST /api/v1/patch-notes) and the admin page.
CREATE TABLE IF NOT EXISTS patch_notes (
    id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    guild_id     BIGINT      NOT NULL,
    game_id      INTEGER     NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    title        TEXT        NOT NULL,
    version      TEXT,
    summary      TEXT        NOT NULL,
    highlights   JSONB       NOT NULL DEFAULT '[]'::jsonb,
    url          TEXT,
    published_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    posted_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    source       TEXT        NOT NULL DEFAULT 'grok'
);
CREATE INDEX IF NOT EXISTS patch_notes_guild_idx ON patch_notes (guild_id, published_at DESC);

-- Written by Grok Bot through the site's API (POST /api/v1/suggestions) and the admin page.
CREATE TABLE IF NOT EXISTS suggestions (
    id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    guild_id     BIGINT      NOT NULL,
    name         TEXT        NOT NULL,
    rawg_slug    TEXT,
    rawg_id      INTEGER,
    genres       JSONB       NOT NULL DEFAULT '[]'::jsonb,
    reason       TEXT        NOT NULL,
    similar_to   JSONB       NOT NULL DEFAULT '[]'::jsonb,
    platforms    JSONB       NOT NULL DEFAULT '[]'::jsonb,
    release_date DATE,
    url          TEXT,
    suggested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    source       TEXT        NOT NULL DEFAULT 'grok'
);
CREATE INDEX IF NOT EXISTS suggestions_guild_idx ON suggestions (guild_id, suggested_at DESC);
